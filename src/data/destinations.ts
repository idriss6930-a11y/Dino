type Input = {
  tmax: Twelve<number>;
  tmin: Twelve<number>;
  precip: Twelve<number>;
  crowd: Twelve<1 | 2 | 3>;
  price: Twelve<number>;
  cost: DailyCosts;
  events?: DestinationEvent[];
  rainy?: Month[];
  hot?: Month[];
  cold?: Month[];
  aurora?: Month[];
  notes?: string[];
  traps?: string[];
  gems?: string[];
  gem?: boolean;
};

function d(
  slug: string,
  fr: string,
  en: string,
  countryIso: string,
  lat: number,
  lon: number,
  timeZone: string,
  airports: string[],
  currency: string,
  tags: Tag[],
  summary: string,
  i: Input,
): Destination {
  return {
    slug,
    name: { fr, en },
    countryIso,
    lat,
    lon,
    timeZone,
    airports,
    currency,
    tags,
    summary,
    hiddenGem: i.gem ?? false,
    climate: { tmax: i.tmax, tmin: i.tmin, precip: i.precip },
    crowd: i.crowd,
    priceIndex: i.price,
    costs: i.cost,
    events: i.events ?? [],
    seasons: { rainy: i.rainy, hot: i.hot, cold: i.cold, aurora: i.aurora, notes: i.notes },
    traps: i.traps ?? [],
    gems: i.gems ?? [],
  };
}

